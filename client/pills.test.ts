import { expect,it,vi } from "vitest";
import { buttonFor } from "./pills";
import type { PluginClientContext } from "@getpaseo/plugin/client";
import { StateViewSchema } from "../shared/model";
import { setAgentAccount } from "../shared/rpc";
import type { ZeroSubStore } from "./store";
vi.mock("react-native",()=>({NativeModules:{},Platform:{OS:"web"}}));
it("opens an account menu and switches only through the selected action",async()=>{
 const openScreen=vi.fn(), rpc=vi.fn().mockResolvedValue({failed:[]});
 const accounts=["a","b"].map(id=>({id,family:"codex",label:id,kind:"main",email:null,plan:null,organization:null,status:"ready",isDefault:id==="a",limitedUntil:null,usage:null,agentCount:1,home:null}));
 const state=StateViewSchema.parse({accounts,agents:[],logins:[],providers:{codex:"codex"},canReopen:true,showComposerPill:true,warnings:[]});
 const button=buttonFor({openScreen} as unknown as PluginClientContext,{rpc} as unknown as ZeroSubStore,state,{id:"agent-a",workspaceId:"workspace-a",provider:"codex"});
 expect(button?.behavior.kind).toBe("menu");
 if(button?.behavior.kind!=="menu")throw new Error("Expected menu");
 const entries=button.behavior.items;
 const current=entries.find(e=>e.id==="account-0");
 expect(current?.kind==="item" && current.disabled).toBe(true);
 const other=entries.find(e=>e.id==="account-1");
 if(other?.kind!=="item" || other.behavior.kind!=="action")throw new Error("Expected account action");
 await other.behavior.onPress();
 expect(rpc).toHaveBeenCalledExactlyOnceWith(setAgentAccount,{agentId:"agent-a",accountId:"b"});
 expect(openScreen).not.toHaveBeenCalled();
});
